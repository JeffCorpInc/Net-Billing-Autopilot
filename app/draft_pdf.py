"""Draft Application PDF generator using ReportLab with watermark and Schedule-II fields."""

import io
from datetime import datetime, timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.pdfgen import canvas
from reportlab.platypus import (
    HRFlowable,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.config import DOC_LABELS, RULES_AS_OF
from app.models import CaseReport, Pack


class NumberedCanvasWithWatermark(canvas.Canvas):
    """Canvas that draws running footers and a diagonal draft watermark."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_watermark_and_footer(num_pages)
            super().showPage()
        super().save()

    def draw_watermark_and_footer(self, page_count):
        self.saveState()

        # Diagonal Light Grey Watermark
        self.setFont("Helvetica-Bold", 32)
        self.setFillColor(colors.Color(0.85, 0.85, 0.88, alpha=0.35))
        self.translate(A4[0] / 2.0, A4[1] / 2.0)
        self.rotate(35)
        self.drawCentredString(0, 0, "DRAFT — customer must review and sign")
        self.restoreState()

        # Running Footer
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        footer_text = (
            f"Rules as of {RULES_AS_OF} · Synthetic data · Generated by NetBill Assist — not submitted"
        )
        self.drawString(36, 25, footer_text)
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(A4[0] - 36, 25, page_str)
        self.restoreState()


def mask_cnic(cnic_no: str) -> str:
    """Mask middle digits of CNIC (e.g. 42101-*******-1)."""
    parts = cnic_no.split("-")
    if len(parts) == 3:
        return f"{parts[0]}-*******-{parts[2]}"
    if len(cnic_no) >= 13:
        return f"{cnic_no[:5]}-*******-{cnic_no[-1]}"
    return cnic_no


def mask_ref_no(ref_no: str) -> str:
    """Mask middle digits of reference number (e.g. 01********12)."""
    if len(ref_no) >= 14:
        return f"{ref_no[:2]}********{ref_no[-2:]}"
    return ref_no


def generate_draft_pdf_bytes(pack: Pack, report: CaseReport | None = None) -> bytes:
    """Generate complete A4 PDF bytes for the draft application."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=36,
        rightMargin=36,
        topMargin=36,
        bottomMargin=45,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=15,
        leading=18,
        textColor=colors.HexColor("#0F172A"),
        spaceAfter=4,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#64748B"),
        spaceAfter=12,
    )
    sec_style = ParagraphStyle(
        "SectionHeader",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=10.5,
        leading=14,
        textColor=colors.HexColor("#0F172A"),
        spaceBefore=8,
        spaceAfter=4,
    )
    body_style = ParagraphStyle(
        "DocBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#1E293B"),
    )
    bold_body = ParagraphStyle(
        "BoldBody",
        parent=body_style,
        fontName="Helvetica-Bold",
    )

    story = []

    # Title & Subtitle
    story.append(Paragraph("DRAFT — Net-Billing Application (Schedule-II fields)", title_style))
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    story.append(Paragraph(f"Case ID: <b>{pack.case_id}</b> · Generated: {now_str}", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#E2E8F0"), spaceAfter=8))

    # 1. Applicant Section
    story.append(Paragraph("1. Applicant Information", sec_style))
    app_data = [
        [
            Paragraph("Full Name:", bold_body),
            Paragraph(pack.cnic.name, body_style),
            Paragraph("Father's Name:", bold_body),
            Paragraph(pack.cnic.father_name, body_style),
        ],
        [
            Paragraph("CNIC (Masked):", bold_body),
            Paragraph(mask_cnic(pack.cnic.cnic_no), body_style),
            Paragraph("CNIC Expiry:", bold_body),
            Paragraph(pack.cnic.expiry, body_style),
        ],
    ]
    t_app = Table(app_data, colWidths=[95, 165, 95, 165])
    t_app.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("PADDING", (0, 0), (-1, -1), 4),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
    ]))
    story.append(t_app)
    story.append(Spacer(1, 6))

    # 2. Premises Information
    story.append(Paragraph("2. Installation Premises", sec_style))
    prem_data = [
        [
            Paragraph("Address:", bold_body),
            Paragraph(pack.bill.address, body_style),
            Paragraph("Ownership Type:", bold_body),
            Paragraph(pack.ownership.type.replace("_", " ").title(), body_style),
        ],
        [
            Paragraph("Occupancy:", bold_body),
            Paragraph("Tenant" if pack.is_tenant else "Owner-Occupied", body_style),
            Paragraph("Deed Owner:", bold_body),
            Paragraph(pack.ownership.owner_name, body_style),
        ],
    ]
    t_prem = Table(prem_data, colWidths=[95, 165, 95, 165])
    t_prem.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("PADDING", (0, 0), (-1, -1), 4),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
    ]))
    story.append(t_prem)
    story.append(Spacer(1, 6))

    # 3. Electricity Connection
    story.append(Paragraph("3. Electricity Connection (K-Electric)", sec_style))
    elec_data = [
        [
            Paragraph("Account Ref:", bold_body),
            Paragraph(mask_ref_no(pack.bill.reference_no), body_style),
            Paragraph("Consumer Name:", bold_body),
            Paragraph(pack.bill.consumer_name, body_style),
        ],
        [
            Paragraph("Sanctioned Load:", bold_body),
            Paragraph(f"{pack.bill.sanctioned_load_kw} kW", body_style),
            Paragraph("Connected Load:", bold_body),
            Paragraph(f"{pack.bill.connected_load_kw} kW", body_style),
        ],
        [
            Paragraph("Tariff:", bold_body),
            Paragraph(pack.bill.tariff, body_style),
            Paragraph("Connection Phase:", bold_body),
            Paragraph(pack.bill.connection_phase, body_style),
        ],
    ]
    t_elec = Table(elec_data, colWidths=[95, 165, 95, 165])
    t_elec.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("PADDING", (0, 0), (-1, -1), 4),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
    ]))
    story.append(t_elec)
    story.append(Spacer(1, 6))

    # 4. Proposed Solar System
    story.append(Paragraph("4. Proposed Solar Generation Facility", sec_style))
    sys_data = [
        [
            Paragraph("Proposed Capacity:", bold_body),
            Paragraph(f"{pack.system.proposed_kw} kW", body_style),
            Paragraph("Inverter Capacity:", bold_body),
            Paragraph(f"{pack.system.inverter_kw} kW", body_style),
        ],
        [
            Paragraph("Panel Specifications:", bold_body),
            Paragraph(f"{pack.system.panel_count} panels × {pack.system.panel_watt} W", body_style),
            Paragraph("Estimated Fee:", bold_body),
            Paragraph(f"Rs {int(pack.system.proposed_kw * 1000):,} (Rs 1,000/kW)", body_style),
        ],
    ]
    t_sys = Table(sys_data, colWidths=[95, 165, 95, 165])
    t_sys.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("PADDING", (0, 0), (-1, -1), 4),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
    ]))
    story.append(t_sys)
    story.append(Spacer(1, 6))

    # 5. Documents Checklist Table
    story.append(Paragraph("5. Document Completeness Checklist", sec_style))
    base_docs = [
        "cnic", "bill", "ownership", "single_line_diagram", "affidavit",
        "vendor_checklist", "inverter_datasheet", "inverter_settings_letter"
    ]
    if pack.is_tenant:
        base_docs.append("noc")
    if pack.system.proposed_kw >= 250:
        base_docs.append("load_flow_study")
    if pack.applicant_type == "commercial" and pack.system.proposed_kw >= 250:
        base_docs.extend(["ntn", "form_29"])

    doc_rows = [[Paragraph("Document Name", bold_body), Paragraph("Status", bold_body)]]
    for dkey in base_docs:
        label = DOC_LABELS.get(dkey, dkey.replace("_", " ").title())
        is_p = dkey in pack.docs_present
        status_p = Paragraph(
            "<font color='#059669'><b>PRESENT</b></font>" if is_p else "<font color='#E11D48'><b>MISSING</b></font>",
            body_style
        )
        doc_rows.append([Paragraph(label, body_style), status_p])

    t_docs = Table(doc_rows, colWidths=[360, 160])
    t_docs.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
        ("PADDING", (0, 0), (-1, -1), 3),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
    ]))
    story.append(t_docs)
    story.append(Spacer(1, 6))

    # 6. Compliance Status Summary
    story.append(Paragraph("6. Compliance Verification Summary", sec_style))
    ov_status = report.overall if report else "PENDING"
    fails = [r for r in report.results if r.status in ["FAIL", "UNSURE"]] if report else []

    status_color = "#059669" if ov_status == "READY" else "#E11D48" if ov_status == "NOT_READY" else "#D97706"
    summary_text = f"Overall Status: <font color='{status_color}'><b>{ov_status}</b></font>"
    if fails:
        fail_items = ", ".join(f"{f.id} ({f.name})" for f in fails)
        summary_text += f"<br/>Issues Detected: {fail_items}"
    else:
        summary_text += "<br/>All verified checks pass regulatory constraints."

    story.append(Paragraph(summary_text, body_style))
    story.append(Spacer(1, 8))

    # 7. Customer Declaration & Signature Box
    story.append(Paragraph("7. Applicant Declaration", sec_style))
    decl_text = (
        "I hereby declare that the information provided above is true and correct to the best of my knowledge. "
        "I confirm that the solar system meets K-Electric inter-connection standards and agree to adhere to NEPRA "
        "Prosumer Regulations 2026. This draft has been reviewed by me prior to final submission."
    )
    story.append(Paragraph(decl_text, body_style))
    story.append(Spacer(1, 10))

    sig_data = [
        [
            Paragraph("<b>Applicant Signature:</b>", body_style),
            Paragraph("<b>Date:</b>", body_style),
            Paragraph("<b>Installer Stamp & Ref:</b>", body_style),
        ],
        [
            Spacer(1, 24),
            Spacer(1, 24),
            Spacer(1, 24),
        ],
    ]
    t_sig = Table(sig_data, colWidths=[170, 170, 180])
    t_sig.setStyle(TableStyle([
        ("LINEBELOW", (0, 1), (0, 1), 1, colors.HexColor("#94A3B8")),
        ("LINEBELOW", (1, 1), (1, 1), 1, colors.HexColor("#94A3B8")),
        ("LINEBELOW", (2, 1), (2, 1), 1, colors.HexColor("#94A3B8")),
        ("PADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(t_sig)

    doc.build(story, canvasmaker=NumberedCanvasWithWatermark)
    return buf.getvalue()

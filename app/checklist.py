def extract_numbers(text: str) -> set[str]:
    """Extract all digit strings from text for faithfulness comparison."""
    return set(re.findall(r"\b\d+(?:\.\d+)?\b", text))


def verify_faithfulness_gate(
    input_issues: list[dict[str, str]],
    llm_items: list[dict[str, str]],
) -> tuple[bool, str | None]:
    """Strictly verify LLM checklist output against input issues.

    Rejection conditions:
    (a) Any check_id in output is not in input set.
    (b) Any input check_id is missing from output.
    (c) Output item count differs from input issues count.
    (d) Any number in text does not appear in that issue's detail or citation.
    """
    input_ids = [issue["check_id"] for issue in input_issues]
    input_set = set(input_ids)

    if len(llm_items) != len(input_issues):
        return False, f"Item count mismatch: expected {len(input_issues)}, got {len(llm_items)}"

    output_ids = [item.get("check_id") for item in llm_items]
    if output_ids != input_ids:
        # Check specific mismatch
        extra = set(output_ids) - input_set
        missing = input_set - set(output_ids)
        if extra:
            return False, f"Extraneous check_id generated by LLM: {extra}"
        if missing:
            return False, f"Missing check_id in LLM output: {missing}"
        return False, "Order or identity of check_ids differs from input issues"

    # Verify no hallucinated numbers
    for issue, item in zip(input_issues, llm_items):
        allowed_numbers = extract_numbers(issue["detail"] + " " + issue["citation"] + " " + issue["check_id"])
        text_numbers = extract_numbers(item.get("text", ""))
        hallucinated = text_numbers - allowed_numbers
        if hallucinated:
            return False, f"Hallucinated numbers in check {issue['check_id']}: {hallucinated}"

    return True, None


def generate_fallback_checklist(
    failed_checks: list[Any],
    lang: str = "en",
) -> list[ChecklistItem]:
    """Build deterministic template checklist items for failed checks."""
    templates = CHECKLIST_TEMPLATES_UR if lang == "ur" else CHECKLIST_TEMPLATES_EN
    items = []
    for chk in failed_checks:
        cid = chk.id if hasattr(chk, "id") else chk.get("id", "")
        key = chk.key if hasattr(chk, "key") else chk.get("key", "")
        default_tpl = (
            f"براہ کرم مسئلہ حل کریں: {chk.detail} [{chk.citation}]"
            if lang == "ur"
            else f"Please address issue: {chk.detail} [{chk.citation}]"
        )
        text = templates.get(key, default_tpl)
        items.append(ChecklistItem(check_id=cid, text=text))
    return items


def generate_customer_checklist(
    case_id: str,
    report: CaseReport,
    lang: str = "en",
) -> ChecklistResult:
    """Generate bilingual customer checklist with faithfulness gate protection."""
    settings = get_settings()

    # Identify failed or unsure checks
    failed_checks = [
        r for r in report.results
        if r.status in ["FAIL", "UNSURE"] and r.id not in ["R6"]
    ]

    # Clean case: all passed
    if not failed_checks:
        clean_text = (
            "تمام جانچ کے مراحل مکمل ہو چکے ہیں۔ مسودہ آپ کے جائزے اور دستخط کے لیے تیار ہے۔"
            if lang == "ur"
            else "All checks passed. The draft is ready for your review and signature."
        )
        return ChecklistResult(
            lang=lang,
            items=[ChecklistItem(check_id="ALL_PASS", text=clean_text)],
            gate="skipped",
            gate_reason=None,
            source="code",
        )

    # Prepare redacted input
    input_issues = [
        {"check_id": chk.id, "detail": chk.detail, "citation": chk.citation}
        for chk in failed_checks
    ]
    user_payload = build_l3_checklist_input(input_issues, lang=lang)
    system_prompt = L3_CHECKLIST_SYSTEM_TEMPLATE.format(
        LANG="Urdu" if lang == "ur" else "English"
    )

    llm_out, meta = complete_json(
        system=system_prompt,
        user=json.dumps(user_payload, ensure_ascii=False),
        temperature=0.2,
        case_id=case_id,
        task="L3",
    )

    # Run faithfulness gate
    gate_passed = False
    gate_reason = "No output from LLM provider"

    if llm_out and isinstance(llm_out, dict) and "items" in llm_out:
        raw_items = llm_out["items"]
        if isinstance(raw_items, list):
            gate_passed, gate_reason = verify_faithfulness_gate(input_issues, raw_items)

    if gate_passed:
        items = [
            ChecklistItem(check_id=it["check_id"], text=it["text"])
            for it in llm_out["items"]
        ]
        return ChecklistResult(
            lang=lang,
            items=items,
            gate="passed",
            gate_reason=None,
            source="mock-llm" if meta.get("provider") == "mock" else "llm",
        )
    else:
        # Rejection -> Fall back to deterministic templates
        fallback_items = generate_fallback_checklist(failed_checks, lang=lang)
        return ChecklistResult(
            lang=lang,
            items=fallback_items,
            gate="rejected",
            gate_reason=gate_reason,
            source="template-fallback",
        )
